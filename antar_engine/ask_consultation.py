"""
antar_engine/ask_consultation.py
=================================
Consultation layer for /api/v1/ask — launch sprint 2026-06-03.

Gives /ask the three-part consultation answer on real, deterministic inputs:
  1. VERDICT + TIMING — from a 2-of-3 convergence across Vimshottari (MD/AD),
     Chara dasha, and Varshphal. Python computes the window; Claude narrates.
  2. ACTIONS — generated by Claude FROM the convergence facts (never invented
     dates — the window is pinned in the prompt).
  3. PRACTICES — markable PracticeCards come from the existing practice
     engine (practice_id linkage to practice_log), assembled in main.py.

Shared primitives with /predict: dasha_periods rows (get_dashas_for_chart
shape), varshaphal_table.get_annual_house, detect_concern domain names.
No LLM calls in this module. No prose duplication of /predict's context.
"""

