def _current_dasha_lords(dashas, today):
    """[slice-1b] Running Vimshottari MD + AD lords for the promise engine."""
    md = ad = ""
    for r in _rows(dashas, "vimsottari"):
        lv = _level(r)
        s, e = _win(r)
        if not (s and e and s <= today <= e):
            continue
        if lv in ("mahadasha", "1") and not md:
            md = _lord(r)
        elif lv in ("antardasha", "antar", "2") and not ad:
            ad = _lord(r)
    return md, ad


def _vimshottari_lock(dashas, chart_data, houses, lords, today, horizon):
    """Earliest current/upcoming Vimshottari period whose lord rules or
    occupies a target house. AD windows preferred (tighter)."""
    planets = (chart_data or {}).get("planets") or {}

    def qualifies(p):
        if not p:
            return False
        if p in lords:
            return True
        return (planets.get(p) or {}).get("house") in houses

    best = None
    for want_ad in (True, False):
        for r in _rows(dashas, "vimsottari"):
            lv = _level(r)
            is_ad = lv in ("antardasha", "antar", "2")
            is_md = lv in ("mahadasha", "1")
            if want_ad and not is_ad:
                continue
            if not want_ad and not is_md:
                continue
            s, e = _win(r)
            if not s or not e or e < today or s > horizon:
                continue
            p = _lord(r)
            if qualifies(p):
                cs, ce = max(s, today), min(e, horizon)
                if best is None or cs < best[1]:
                    kind = "sub-chapter" if is_ad else "chapter"
                    role = "rules" if p in lords else "occupies"
                    best = (p, cs, ce, f"{p} {kind} {role} a target area, {_fmt_window(cs, ce)}")
        if best:
            break
    if best:
        return {"active": True, "start": best[1], "end": best[2], "why": best[3], "planet": best[0]}
    return {"active": False, "start": None, "end": None, "why": "no period lord touches the target areas in the horizon", "planet": ""}


def _next_vim_window(dashas, chart_data, houses, lords, after, horizon):
    """Earliest qualifying Vimshottari window STARTING after `after` —
    surfaces the next opening when the current window is the tail of an
    ending chapter (e.g. funding: Mars MD ends Aug 2026, Rahu in the gains
    area takes over)."""
    planets = (chart_data or {}).get("planets") or {}

    def qualifies(p):
        if not p:
            return False
        if p in lords:
            return True
        return (planets.get(p) or {}).get("house") in houses

    best = None
    for r in _rows(dashas, "vimsottari"):
        lv = _level(r)
        if lv not in ("antardasha", "antar", "2", "mahadasha", "1"):
            continue
        s, e = _win(r)
        # s >= after keeps same-day chapter handoffs (e.g. Mars ends Aug 13,
        # Rahu starts Aug 13) — but skip rows already underway before `after`
        if not s or not e or s < after or s > horizon:
            continue
        p = _lord(r)
        if qualifies(p) and (best is None or s < best[1]):
            kind = "sub-chapter" if lv in ("antardasha", "antar", "2") else "chapter"
            role = "rules" if p in lords else "occupies"
            best = (p, s, min(e, horizon), f"{p} {kind} ({role} a target area) opens {s.strftime('%b %Y')}")
    if best:
        return {"planet": best[0], "start": best[1], "end": best[2],
                "label": _fmt_window(best[1], best[2]), "why": best[3]}
    return None


