def _chara_lock(dashas, lagna_idx, houses, lords, today, horizon):
    """Earliest current/upcoming Chara sign period that activates a target
    house (sign sits in a target house from lagna, or sign's lord is a
    target-house lord). AD sign periods preferred."""
    best = None
    for want_ad in (True, False):
        for r in _rows(dashas, "jaimini"):
            lv = _level(r)
            is_ad = lv in ("antardasha", "antar", "2")
            is_md = lv in ("mahadasha", "1")
            if want_ad and not is_ad:
                continue
            if not want_ad and not is_md:
                continue
            sign = _lord(r)
            if sign not in SIGNS:
                continue
            s, e = _win(r)
            if not s or not e or e < today or s > horizon:
                continue
            sign_house = (SIGNS.index(sign) - lagna_idx) % 12 + 1
            _by_house = sign_house in houses
            _by_lord = SIGN_LORDS[sign] in lords
            if _by_house or _by_lord:
                cs, ce = max(s, today), min(e, horizon)
                if best is None or cs < best[1]:
                    kind = "sub-period" if is_ad else "period"
                    if _by_house:
                        reason = f"sits in target house {sign_house}"
                    else:
                        reason = f"its lord {SIGN_LORDS[sign]} rules a target area"
                    best = (sign, cs, ce,
                            f"{sign} {kind} {reason}, {_fmt_window(cs, ce)}")
        if best:
            break
    if best:
        return {"active": True, "start": best[1], "end": best[2], "why": best[3],
                "planet": SIGN_LORDS.get(best[0], "")}
    return {"active": False, "start": None, "end": None, "why": "no sign period activates the target areas in the horizon", "planet": ""}


def _varshphal_lock(chart_data, birth_date, houses, lords, karakas, today):
    """Does this Varshphal year send a domain-relevant planet (target-house
    lord or natural karaka) into a target annual house? Window = the annual
    chart's validity (birthday to birthday). Same get_annual_house as /predict."""
    born = _parse_d(birth_date)
    if not born:
        return {"active": False, "start": None, "end": None, "why": "birth date unavailable"}
    try:
        from antar_engine.varshaphal_table import get_annual_house
    except Exception:
        return {"active": False, "start": None, "end": None, "why": "varshphal table unavailable"}

    age = (today - born).days // 365
    try:
        last_bday = born.replace(year=today.year)
    except ValueError:  # Feb 29
        last_bday = born.replace(year=today.year, day=28)
    if last_bday > today:
        last_bday = last_bday.replace(year=last_bday.year - 1)
    next_bday = last_bday.replace(year=last_bday.year + 1)

    relevant = set(lords) | set(karakas)
    hits, hit_planets = [], []
    for p, d in ((chart_data or {}).get("planets") or {}).items():
        nh = d.get("house") if isinstance(d, dict) else None
        if nh and 1 <= nh <= 12 and p in relevant:
            ah = get_annual_house(nh, age)
            if ah in houses:
                hits.append(f"{p} lands in annual house {ah}")
                hit_planets.append(p)
    if hits:
        return {"active": True, "start": last_bday, "end": next_bday,
                "why": "; ".join(hits[:3]) + f", valid {_fmt_window(last_bday, next_bday)}",
                "planet": hit_planets[0]}
    return {"active": False, "start": last_bday, "end": next_bday,
            "why": "this year's chart does not move relevant planets into the target areas",
            "planet": ""}


