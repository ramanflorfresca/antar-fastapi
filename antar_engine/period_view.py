def _span_lbl(i: dict, lang: str, horizon_end: Optional[date] = None) -> str:
    """The stretch an item really runs, for the week view: "until Dec 31" when its end is known, "ongoing" when it runs to the end of the
    range we looked at (so we never claim an end date we did not find)."""
    tx = TX[lang]
    try:
        e_ = date.fromisoformat(i["end"][:10])
    except Exception:
        return i.get("label")
    if horizon_end is not None and e_ >= horizon_end - timedelta(days=3):
        return tx["ongoing"]
    return f"{tx['until']} {_lbl(e_, lang)}"


def _a(word: str, lang: str) -> str:
    """"a" or "an" for the English chapter line ("an intellect chapter")."""
    return "an" if lang == "en" and word[:1].lower() in "aeiou" else "a"


def _lbl(d: date, lang: str) -> str:
    """"Oct 31" / "31 oct": a date the app can show as is."""
    return f"{SHORT[lang][d.month - 1]} {d.day}" if lang == "en" else f"{d.day} {SHORT[lang][d.month - 1]}"


def _range_lbl(s_: date, e_: date, lang: str) -> str:
    if s_ == e_:
        return _lbl(s_, lang)
    return f"{_lbl(s_, lang)} {TX[lang]['to']} {_lbl(e_, lang)}"


def _clip(i: dict, start: date, end: date, lang: str) -> dict:
    """The item with its dates clipped to the window and a ready-made label, so the same long-running line reads with the part that falls here."""
    try:
        s_ = max(date.fromisoformat(i["start"][:10]), start)
        e_ = min(date.fromisoformat(i["end"][:10]), end)
    except Exception:
        return i
    return {**i, "start": s_.isoformat(), "end": e_.isoformat(), "label": _range_lbl(s_, e_, lang)}


def _domain_reads(out_areas: List[dict], past: bool, lang: str) -> List[dict]:
    """The five-area read (money, love, career, health, mind), the same shape as the day view: a tone and one or two lines each."""
    tx = TX[lang]
    reads, used = [], set()
    for key, keys in DOMAINS:
        mine = [a for a in out_areas if a["key"] in keys]
        lean = [i for a in mine for i in a["lean_in"] if i["text"] not in used]
        watch = [i for a in mine for i in a["watch"] if i["text"] not in used]
        tone = _tone(bool(lean), bool(watch))
        lines = []
        if tone in ("good", "mixed") and lean:
            lines.append(lean[0])
        if tone in ("care", "mixed") and watch:
            lines.append(watch[0])
        used.update(l["text"] for l in lines)
        reads.append({"key": key, "label": tx["domain_" + key], "tone": tone, "verdict": VERDICT_OF[tone],
                      "lines": [{"text": l["text"], "label": l.get("label")} for l in lines],
                      "quiet": None if lines else (tx["quiet_past"] if past else tx["quiet"])})
    return reads


def _do_avoid(out_areas: List[dict], lang: str, scope: str):
    """Do: one step per strong area. Avoid: each care item with what to do instead. Past windows get neither (the caller skips this)."""
    lean = _lean_steps()
    do, seen = [], set()
    for a in out_areas:
        if a["lean_in"] and a["key"] in lean:
            t = lean[a["key"]][1 if lang == "es" else 0]
            if t not in seen:
                seen.add(t)
                do.append({"area": a["label"], "text": t})
    avoid, seen = [], set()
    for a in out_areas:
        for i in a["watch"][:1]:
            if i["text"] not in seen:
                seen.add(i["text"])
                avoid.append({"area": a["label"], "text": i["text"], "instead": i.get("do"), "label": i.get("label")})
    return do[:4], avoid[:4]


def _week_blocks(start: date, end: date) -> List[tuple]:
    blocks, d = [], start
    while d <= end:
        e = min(d + timedelta(days=6), end)
        if (end - e).days < 3:                      # fold a short tail into the last block
            e = end
        blocks.append((d, e))
        d = e + timedelta(days=1)
    return blocks


def _best_avoid_week(ctx, start: date, end: date, turns: List[dict], lang: str, past: bool,
                     day_scores: Optional[dict] = None) -> dict:
    """One best and one quieter week of the month and its easy / slow days, plus the dated turns inside each week. When the day scores
    are given (the same score the day strip and the Today card use: good >= 7, tough < 4) the days come from them, so the month can
    never call a day best that the strip marks tough; otherwise from the Moon-based easy / slow days."""
    moon = ctx.planets.get("Moon")
    if moon is None and not day_scores:
        return {}
    tx = TX[lang]
    scored = []
    for (a, b) in _week_blocks(start, end):
        if not past and b < ctx.today:
            continue        # a stretch that is already over is not "the best week" to act in; only today and later count
        a = a if past else max(a, ctx.today)
        sc, d, good_days, slow_days = 0, a, [], []
        while d <= b:
            if day_scores and day_scores.get(d.isoformat()) is not None:
                v = day_scores[d.isoformat()]
                st = "good" if v >= 7 else ("bad" if v < 4 else "mid")
            else:
                st = gochara.state_on(moon.sign, d)["Moon"]["state"] if moon is not None else "mid"
            if st == "good":
                sc += 1
                good_days.append(d.isoformat())
            elif st == "bad":
                sc -= 1
                slow_days.append(d.isoformat())
            d += timedelta(days=1)
        for t in turns:
            if a.isoformat() <= t["date"] <= b.isoformat():
                sc += 2 if t["tone"] == "good" else (-2 if t["tone"] == "care" else 0)
        scored.append((sc, a, b, good_days, slow_days))
    if len(scored) < 2:
        return {}
    best, worst = max(scored, key=lambda x: (x[0], -x[1].toordinal())), min(scored, key=lambda x: (x[0], x[1].toordinal()))
    out = {}
    if best[0] > worst[0]:
        out["best_week"] = {"start": best[1].isoformat(), "end": best[2].isoformat(), "label": _range_lbl(best[1], best[2], lang),
                            "title": tx["best_week_past"] if past else tx["best_week"],
                            "text": tx["best_text_past"] if past else tx["best_text"]}
        out["best_days"] = best[3]
        out["avoid_week"] = {"start": worst[1].isoformat(), "end": worst[2].isoformat(), "label": _range_lbl(worst[1], worst[2], lang),
                             "title": tx["avoid_week_past"] if past else tx["avoid_week"],
                             "text": tx["avoid_text_past"] if past else tx["avoid_text"]}
        out["slow_days"] = worst[4][:4]
    return out


def _best_avoid_month(cells: List[dict], turns: List[dict], lang: str, past: bool) -> dict:
    tx = TX[lang]
    score = {"good": 2, "steady": 0, "tough": -2}
    sc = {}
    for c in cells:
        n = score[c["verdict"]]
        for t in turns:
            if t["date"][:7] == c["month"]:
                n += 1 if t["tone"] == "good" else (-1 if t["tone"] == "care" else 0)
        sc[c["month"]] = n
    best, worst = max(cells, key=lambda c: (sc[c["month"]], -int(c["month"][5:]))), min(cells, key=lambda c: (sc[c["month"]], int(c["month"][5:])))
    out = {}
    if sc[best["month"]] > sc[worst["month"]]:
        out["best_month"] = {"month": best["month"], "label": best["label"],
                             "title": tx["best_month_past"] if past else tx["best_month"],
                             "text": tx["best_text_past"] if past else tx["best_text"]}
        out["avoid_month"] = {"month": worst["month"], "label": worst["label"],
                              "title": tx["avoid_month_past"] if past else tx["avoid_month"],
                              "text": tx["avoid_text_past"] if past else tx["avoid_text"]}
    return out


def _key_dates(turns: List[dict], chapters: List[dict], start: date, lang: str) -> List[dict]:
    """Dated turns and chapter changes, one sorted list with ready-made labels."""
    tx = TX[lang]
    items = [{"date": t["date"], "text": t["text"], "tone": t["tone"], "kind": "turn"} for t in turns]
    for c in chapters:
        if c["start"] > start.isoformat():
            items.append({"date": c["start"], "text": tx["chapter_begins"].format(a=_a((c.get("theme") or ""), lang).capitalize() if lang == "en" else "", theme=(c.get("theme") or "").lower(), nature=(c.get("nature") or "").lower()).strip(),
                          "tone": "good" if c.get("nature") == "supportive" else "care", "kind": "chapter"})
    items.sort(key=lambda i: (i["date"], i["kind"]))
    for i in items:
        i["label"] = _lbl(date.fromisoformat(i["date"]), lang)
    return items[:12]


def _tone_of_score(score) -> str:
    """The same bands as the day strip and the Today card: 7 and up good, under 4 tough, else steady."""
    return "good" if score >= 7 else ("tough" if score < 4 else "steady")


def _week_days(ctx, start: date, end: date, turns: List[dict], lang: str, past: bool, day_scores: Optional[dict] = None) -> dict:
    """Seven days with a tone each, one best day and one take-care day. With `day_scores` ({iso date: score}, the same score the day
    strip and the Today card use) the week agrees with them by construction; without, it falls back to the Moon-based easy and slow
    days plus the dated turns."""
    tx = TX[lang]
    days = []
    d = start
    if day_scores:
        while d <= end:
            sc = day_scores.get(d.isoformat())
            days.append((d, sc, _tone_of_score(sc) if sc is not None else "steady"))
            d += timedelta(days=1)
        scored = [(x, sc) for x, sc, _ in days if sc is not None]
        if not scored:
            return {}
        best = max(scored, key=lambda t: (t[1], -t[0].toordinal()))
        care = min(scored, key=lambda t: (t[1], t[0].toordinal()))
        has_pair = best[1] - care[1] >= 2
    else:
        moon = ctx.planets.get("Moon")
        if moon is None:
            return {}
        while d <= end:
            st = gochara.state_on(moon.sign, d)["Moon"]["state"]
            sc = 1 if st == "good" else (-1 if st == "bad" else 0)
            for t in turns:
                if t["date"] == d.isoformat():
                    sc += 2 if t["tone"] == "good" else (-2 if t["tone"] == "care" else 0)
            days.append((d, sc, "good" if sc > 0 else ("tough" if sc < 0 else "steady")))
            d += timedelta(days=1)
        best = max([(x, sc) for x, sc, _ in days], key=lambda t: (t[1], -t[0].toordinal()))
        care = min([(x, sc) for x, sc, _ in days], key=lambda t: (t[1], t[0].toordinal()))
        has_pair = best[1] > care[1]
    out = {"days": [{"date": x.isoformat(), "label": _day_lbl(x, lang), "tone": tone, **({"score": sc} if sc is not None and day_scores else {})}
                    for x, sc, tone in days]}
    if has_pair:
        out["best_day"] = {"date": best[0].isoformat(), "label": _day_lbl(best[0], lang),
                           "title": tx["best_day_past"] if past else tx["best_day"],
                           "text": tx["best_day_text_past"] if past else tx["best_day_text"]}
        out["care_day"] = {"date": care[0].isoformat(), "label": _day_lbl(care[0], lang),
                           "title": tx["care_day_past"] if past else tx["care_day"],
                           "text": tx["care_day_text_past"] if past else tx["care_day_text"]}
        out["headline"] = {"text": f"{out['best_day']['title']} {out['best_day']['label']}. {out['care_day']['title']} {out['care_day']['label']}.",
                           "tone": "care"}
    return out


def build(ctx, lib: dict, life: Optional[dict], scope: str, offset: int, language: str = "en", today: Optional[date] = None,
          day_scores: Optional[dict] = None) -> dict:
    lang = "es" if language == "es" else "en"
    today = today or ctx.today
    start, end = window(scope, offset, today)
    rel = _relation(offset)
    past = rel == "past"
    tx = TX[lang]
    area_defs = focus_view._areas(life)
    try:
        hz_end = date.fromisoformat((lib.get("horizon") or [None, None])[1][:10])
    except Exception:
        hz_end = None
    subj_area = {}
    for key, subjects, labels in area_defs:
        for s_ in subjects:
            subj_area.setdefault(s_, (key, labels[lang]))
    agree_subj = {a["subject"] for a in (lib.get("agree") or []) if _overlaps(a, start, end)}

    flat = []
    for line in ("vimshottari", "jaimini"):
        for tone, kind in (("lean_in", "good"), ("watch", "care")):
            for i in (lib.get(line) or {}).get(tone, []):
                if _overlaps(i, start, end):
                    flat.append({**i, "tone": kind})

    areas = {}
    for i in flat:
        pair = next((subj_area[s_] for s_ in (i.get("subject"),) if s_ in subj_area), None) or \
            next((subj_area[s_] for s_ in (i.get("_subjects") or []) if s_ in subj_area), None)
        if not pair:
            continue
        a = areas.setdefault(pair[0], {"key": pair[0], "label": pair[1], "lean_in": [], "watch": [], "strong": False})
        clipped = _clip(i, start, end, lang)
        if scope == "week":
            clipped = {**clipped, "label": _span_lbl(i, lang, hz_end) if date.fromisoformat(i["end"][:10]) > end else clipped.get("label")}
        item = public_view._item(clipped)
        if past:
            item.pop("do", None)
            item.pop("remedy", None)
        a["lean_in" if i["tone"] == "good" else "watch"].append(item)
        if i.get("subject") in agree_subj:
            a["strong"] = True
    order = {k: n for n, (k, _, _) in enumerate(area_defs)}
    out_areas = []
    for a in sorted(areas.values(), key=lambda x: (not x["strong"], -len(x["lean_in"]), order.get(x["key"], 99))):
        a["lean_in"] = public_view._dedupe(a["lean_in"], 3)
        a["watch"] = public_view._dedupe(a["watch"], 3)
        a["tone"] = _tone(bool(a["lean_in"]), bool(a["watch"]))
        out_areas.append(a)

    low = lambda ls: [ls[0]] + [x[:1].lower() + x[1:] for x in ls[1:]] if ls else ls
    leads = low([a["label"] for a in out_areas if a["tone"] in ("good", "mixed")][:2])
    cares = low([a["label"] for a in out_areas if a["watch"]][:2])
    if leads or cares:
        bits = []
        if leads:
            bits.append((tx["strong_past"] if past else tx["strong"]).format(areas=_join(leads, lang)) + ".")
        if cares:
            bits.append((tx["care_past"] if past else tx["care"]).format(areas=_join(cares, lang)))
        summary = " ".join(bits)
    else:
        summary = tx["none_past"] if past else tx["none"]

    out = {"scope": scope, "offset": offset, "relation": rel, "title": _title(scope, start, lang, end),
           "start": start.isoformat(), "end": end.isoformat(), "verdict": _verdict(out_areas), "summary": summary, "areas": out_areas,
           "chapters": _chapters(ctx, start, end, scope, lang),
           "labels": {"lean_in": tx["lean_past"] if past else tx["lean"], "watch": tx["watch_past"] if past else tx["watch"],
                      "chapters": tx["chapters_past"] if past else tx["chapters"], "look_after": tx["look_after"]}}
    out["turns"] = [{**t, "label": _lbl(date.fromisoformat(t["date"]), lang)} for t in _turns(ctx, area_defs, start, end, past, lang)]
    for c in out["chapters"]:
        c["label"] = _range_lbl(date.fromisoformat(c["start"]), date.fromisoformat(c["end"]), lang)
    out["domains"] = _domain_reads(out_areas, past, lang)
    out["key_dates"] = _key_dates(out["turns"], out["chapters"], start, lang)
    if not past:
        do, avoid = _do_avoid(out_areas, lang, scope)
        if do:
            out["do"] = do
        if avoid:
            out["avoid"] = avoid
        out["labels"].update({"do": tx["do_y"] if scope == "year" else (tx["do_w"] if scope == "week" else tx["do"]),
                              "avoid": tx["avoid_y"] if scope == "year" else (tx["avoid_w"] if scope == "week" else tx["avoid"]),
                              "instead": tx["instead"]})
    else:
        out["labels"].update({"instead": tx["instead"]})
    out["labels"].update({"domains": tx["domains"], "key_dates": tx["key_dates"]})
    if scope == "week":
        out.update(_week_days(ctx, start, end, out["turns"], lang, past, day_scores))
        out["labels"]["running"] = tx["running"]
    if scope == "month":
        out.update(_best_avoid_week(ctx, start, end, out["turns"], lang, past, day_scores))
    if scope == "year":
        out["months"] = _month_cells(
            [{"start": i["start"], "end": i["end"], "tone": i["tone"]} for i in flat], start.year, lang)
        out.update(_best_avoid_month(out["months"], out["turns"], lang, past))
    try:
        from antar_engine import area_paragraph as _ap
        _by = {a["key"]: a for a in out_areas}
        _best = out.get("best_week") or out.get("best_month") or out.get("best_day")
        _avoid = out.get("avoid_week") or out.get("avoid_month") or out.get("care_day")
        for dom, (_k, _keys) in zip(out["domains"], DOMAINS):
            dom["paragraph"] = _ap.paragraph(dom, scope=scope, relation=rel, lang=lang, areas_by_key=_by, area_keys=_keys,
                                             turns=out["turns"], best=_best, avoid=_avoid, steps=_step_by_area(lang))
    except Exception as _e:
        print(f"[period] paragraphs non-fatal: {_e}")
    if not past:
        w = public_view.wellness(lib.get("wellness"))
        if w and w.get("themes"):
            out["care"] = w
    return out
