def window(scope: str, offset: int, today: date) -> Tuple[date, date]:
    if scope == "year":
        y = today.year + offset
        return date(y, 1, 1), date(y, 12, 31)
    idx = today.year * 12 + (today.month - 1) + offset
    y, m = divmod(idx, 12)
    return date(y, m + 1, 1), date(y, m + 1, monthrange(y, m + 1)[1])


def _relation(offset: int) -> str:
    return "past" if offset < 0 else ("next" if offset > 0 else "current")


def _title(scope: str, start: date, lang: str) -> str:
    if scope == "year":
        return TX[lang]["title_y"].format(year=start.year)
    t = TX[lang]["title_m"].format(month=MONTHS[lang][start.month - 1], year=start.year)
    return t[:1].upper() + t[1:]


def _join(names: List[str], lang: str) -> str:
    if len(names) <= 1:
        return "".join(names)
    return (", ".join(names[:-1])) + (" y " if lang == "es" else " and ") + names[-1]


def _overlaps(i: dict, start: date, end: date) -> bool:
    try:
        s, e = date.fromisoformat(i["start"][:10]), date.fromisoformat(i["end"][:10])
    except Exception:
        return False
    return s <= end and e >= start


def _chapters(ctx, start: date, end: date, scope: str, lang: str) -> List[dict]:
    """Sub-period chapters inside the window: a month shows the shortest chapters, a year the months-long ones. Theme and nature in plain words."""
    rows = ctx.vim
    if not rows:
        return []
    s0, e0 = datetime(start.year, start.month, start.day), datetime(end.year, end.month, end.day) + timedelta(days=1)
    out = []
    for ad in [r for r in rows if r["level"] == "ad" and r["end"] > s0 and r["start"] < e0]:
        for pd in vl.subdivide(ad["lord"], ad["start"], ad["end"]):
            if pd["end"] <= s0 or pd["start"] >= e0:
                continue
            spans = vl.subdivide(pd["lord"], pd["start"], pd["end"]) if scope == "month" else [pd]
            for sp in spans:
                if sp["end"] <= s0 or sp["start"] >= e0:
                    continue
                blk = M.planet(sp["lord"], lang) or {}
                out.append({"start": max(sp["start"], s0).date().isoformat(), "end": min(sp["end"], e0 - timedelta(days=1)).date().isoformat(),
                            "theme": blk.get("name"), "nature": blk.get("nature")})
    return out


def _tone(has_good: bool, has_bad: bool) -> str:
    return "mixed" if (has_good and has_bad) else ("good" if has_good else ("care" if has_bad else "quiet"))


def _month_cells(items: List[dict], year: int, lang: str) -> List[dict]:
    cells = []
    for m in range(1, 13):
        ms, me = date(year, m, 1), date(year, m, monthrange(year, m)[1])
        hit = [i for i in items if _overlaps(i, ms, me)]
        cells.append({"month": f"{year}-{m:02d}", "label": SHORT[lang][m - 1],
                      "tone": _tone(any(i["tone"] == "good" for i in hit), any(i["tone"] == "care" for i in hit))})
    return cells


def _turns(ctx, area_defs, start: date, end: date, past: bool, lang: str) -> List[dict]:
    """Dated moments a slow-moving influence enters or leaves an area of life inside the window (all areas), plain words."""
    try:
        ctx2 = type(ctx)(ctx.chart_data, ctx.birth_date, ctx.vim_rows, today=start - timedelta(days=1),
                         birth_time_accuracy=ctx.birth_time_accuracy, gender=ctx.gender)
    except Exception:
        return []
    months = ((end - start).days + 1) / 30.4
    out = []
    for key, subjects, labels in area_defs:
        for t in focus_plan.turning_points(ctx2, labels[lang], subjects, months, lang):
            if t["date"] > end.isoformat():
                continue
            text = PAST_TURN[lang][t["key"]].format(a=labels[lang].lower()) if past else t["text"]
            out.append({"date": t["date"], "tone": t["kind"], "text": text, "area": key})
    out.sort(key=lambda x: x["date"])
    return out[:12]


def _moon_days(ctx, start: date, end: date) -> dict:
    """The days inside a month that run easy and the days that run slow (Moon-based), as dates."""
    moon = ctx.planets.get("Moon")
    if moon is None:
        return {}
    best, slow = [], []
    d = start
    while d <= end:
        st = gochara.state_on(moon.sign, d)["Moon"]["state"]
        (best if st == "good" else slow if st == "bad" else []).append(d.isoformat())
        d += timedelta(days=1)
    return {"best_days": best, "slow_days": slow}


def build(ctx, lib: dict, life: Optional[dict], scope: str, offset: int, language: str = "en", today: Optional[date] = None) -> dict:
    lang = "es" if language == "es" else "en"
    today = today or ctx.today
    start, end = window(scope, offset, today)
    rel = _relation(offset)
    past = rel == "past"
    tx = TX[lang]
    area_defs = focus_view._areas(life)
    subj_area = {}
    for key, subjects, labels in area_defs:
        for s_ in subjects:
            subj_area.setdefault(s_, (key, labels[lang]))
    agree_subj = {a["subject"] for a in (lib.get("agree") or []) if _overlaps(a, start, end)}

    flat = []
    for line in ("vimshottari", "jaimini"):
        for tone, kind in (("lean_in", "good"), ("watch", "care")):
            for i in (lib.get(line) or {}).get(tone, []):
                if _overlaps(i, start, end):
                    flat.append({**i, "tone": kind})

    areas = {}
    for i in flat:
        pair = next((subj_area[s_] for s_ in (i.get("subject"),) if s_ in subj_area), None) or \
            next((subj_area[s_] for s_ in (i.get("_subjects") or []) if s_ in subj_area), None)
        if not pair:
            continue
        a = areas.setdefault(pair[0], {"key": pair[0], "label": pair[1], "lean_in": [], "watch": [], "strong": False})
        item = public_view._item(i)
        if past:
            item.pop("do", None)
            item.pop("remedy", None)
        a["lean_in" if i["tone"] == "good" else "watch"].append(item)
        if i.get("subject") in agree_subj:
            a["strong"] = True
    order = {k: n for n, (k, _, _) in enumerate(area_defs)}
    out_areas = []
    for a in sorted(areas.values(), key=lambda x: (not x["strong"], -len(x["lean_in"]), order.get(x["key"], 99))):
        a["lean_in"] = public_view._dedupe(a["lean_in"], 3)
        a["watch"] = public_view._dedupe(a["watch"], 3)
        a["tone"] = _tone(bool(a["lean_in"]), bool(a["watch"]))
        out_areas.append(a)

    low = lambda ls: [ls[0]] + [x[:1].lower() + x[1:] for x in ls[1:]] if ls else ls
    leads = low([a["label"] for a in out_areas if a["tone"] in ("good", "mixed")][:2])
    cares = low([a["label"] for a in out_areas if a["watch"]][:2])
    if leads or cares:
        bits = []
        if leads:
            bits.append((tx["strong_past"] if past else tx["strong"]).format(areas=_join(leads, lang)) + ".")
        if cares:
            bits.append((tx["care_past"] if past else tx["care"]).format(areas=_join(cares, lang)))
        summary = " ".join(bits)
    else:
        summary = tx["none_past"] if past else tx["none"]

    out = {"scope": scope, "offset": offset, "relation": rel, "title": _title(scope, start, lang),
           "start": start.isoformat(), "end": end.isoformat(), "summary": summary, "areas": out_areas,
           "chapters": _chapters(ctx, start, end, scope, lang),
           "labels": {"lean_in": tx["lean_past"] if past else tx["lean"], "watch": tx["watch_past"] if past else tx["watch"],
                      "chapters": tx["chapters_past"] if past else tx["chapters"], "look_after": tx["look_after"]}}
    out["turns"] = _turns(ctx, area_defs, start, end, past, lang)
    if scope == "month":
        out.update(_moon_days(ctx, start, end))
    if scope == "year":
        out["months"] = _month_cells(
            [{"start": i["start"], "end": i["end"], "tone": i["tone"]} for i in flat], start.year, lang)
    if not past:
        w = public_view.wellness(lib.get("wellness"))
        if w and w.get("themes"):
            out["care"] = w
    return out
